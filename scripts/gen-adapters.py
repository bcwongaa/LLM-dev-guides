HEADING_RE = re.compile(r"^##\s+(.*?)\s*$")
SECTION_TAG_RE = re.compile(r"\s*`\[[a-z-]+\]`\s*$")


def guide_sections(guide_rel: str) -> list[tuple[int, int, str]]:
    """Line ranges for every `## ` section, so skills route to sections not files."""
    lines = (ROOT / guide_rel).read_text().splitlines()
    heads = [
        (n, SECTION_TAG_RE.sub("", mt.group(1)))
        for n, line in enumerate(lines, start=1)
        if (mt := HEADING_RE.match(line))
    ]
    return [
        (start, heads[i + 1][0] - 1 if i + 1 < len(heads) else len(lines), title)
        for i, (start, title) in enumerate(heads)
    ]


def render_skill(m: dict, skill: dict) -> str:
    sections = guide_sections(skill["guide"])
    width = max(len(f"{s}-{e}") for s, e, _ in sections)
    rows = "\n".join(f"{s}-{e}".ljust(width) + f"  {title}" for s, e, title in sections)
    return (
        f"---\n"
        f"name: {skill['id']}\n"
        f"description: \"{skill['description']}\"\n"
        f"---\n"
        f"\n"
        f"Law: `GUIDES_ROOT/{skill['guide']}` (`GUIDES_ROOT` from `AGENTS.md`).\n"
        f"Read **only** the ranges you need: `Read(path, offset=START, limit=END-START+1)`.\n"
        f"Examples live in `REFERENCE.md` beside it.\n"
        f"\n"
        f"{rows}\n"
        f"\n"
        f"Guide and local convention outrank this skill; never paraphrase law from memory.\n"
        f"Protocol still applies: `GUIDES_ROOT/guides/protocol/RULES.md`.\n"
    )


def expected_files(m: dict) -> dict[str, str]:
    suite_agents = render_agents(m, suite=True)
    consumer_agents = render_agents(m, suite=False)
    out = {
        "AGENTS.md": suite_agents,
        "CLAUDE.md": render_claude(m, suite=True),
        "adapters/claude/AGENTS.md": consumer_agents,
        "adapters/claude/CLAUDE.md": render_claude(m, suite=False),
        "adapters/codex/AGENTS.md": consumer_agents,
        "adapters/grok/AGENTS.md": consumer_agents,
    }
    for skill in m["skills"]:
        out[f"adapters/claude/skills/{skill['id']}/SKILL.md"] = render_skill(m, skill)
    return out


def check(m: dict) -> int:
    errors = validate_manifest(m)
    expected = expected_files(m)
    for rel, want in expected.items():
        path = ROOT / rel
        if not path.is_file():
            errors.append(f"{rel}: missing (run python3 scripts/gen-adapters.py --write)")
            continue
        got = path.read_text()
        if got != want:
            errors.append(f"{rel}: drifted from generator output")
    if errors:
        for e in errors:
            print(f"FAIL: {e}", file=sys.stderr)
        print("gen-adapters --check: FAILED", file=sys.stderr)
        return 1
    print(f"gen-adapters --check: OK ({len(expected)} generated files)")
    return 0


def write(m: dict) -> int:
    errors = validate_manifest(m)
    if errors:
        for e in errors:
            print(f"FAIL: {e}", file=sys.stderr)
        return 1
    expected = expected_files(m)
    for rel, want in expected.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(want)
        print(rel)
    print(f"gen-adapters --write: OK ({len(expected)} files)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail if generated files drifted")
    mode.add_argument("--write", action="store_true", help="regenerate files in this repo")
    args = parser.parse_args()
    if not MANIFEST_PATH.is_file():
        print(f"FAIL: manifest missing: {MANIFEST_PATH}", file=sys.stderr)
        return 1
    m = load_manifest()
    return check(m) if args.check else write(m)


if __name__ == "__main__":
    sys.exit(main())

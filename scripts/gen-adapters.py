#!/usr/bin/env python3
"""Generate root maps, consumer adapters, and Claude pointer-skills.

Repository-internal contributor tooling. Not a consumer installer.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST_PATH = ROOT / "adapters" / "manifest.json"
REQUIRED_TOOLS = ("claude", "codex", "grok")
GENERATED_HEADER = "<!-- generated by scripts/gen-adapters.py; do not edit -->\n"


def load_manifest() -> dict:
    return json.loads(MANIFEST_PATH.read_text())


def validate_manifest(m: dict) -> list[str]:
    errors: list[str] = []
    tools = tuple(m.get("tools") or ())
    if tools != REQUIRED_TOOLS:
        errors.append(f"tools must be exactly {list(REQUIRED_TOOLS)}, got {list(tools)}")
    for key in (
        "instruction_authority",
        "implementation_convention",
        "bootstrap",
        "hard_items",
        "always_ask",
        "routes",
        "skills",
        "suite",
        "consumer",
    ):
        if key not in m:
            errors.append(f"missing manifest key: {key}")
    for route in m.get("routes", []) + m.get("suite_only_routes", []):
        rel = route.get("open")
        if not rel or rel.endswith("/"):
            continue
        if not (ROOT / rel).is_file():
            errors.append(f"route target missing: {rel}")
    for skill in m.get("skills", []):
        guide = skill.get("guide")
        if not guide or not (ROOT / guide).is_file():
            errors.append(f"skill {skill.get('id')}: guide missing: {guide}")
    return errors


def route_cell(route: dict, prefix: str) -> str:
    if prefix and route.get("consumer_text"):
        return route["consumer_text"]
    if route.get("text"):
        return route["text"]
    path = route["open"]
    note = route.get("note")
    cell = f"`{prefix}{path}`"
    if note:
        cell += f" ({note})"
    return cell


def routes_table(routes: list[dict], prefix: str = "") -> str:
    lines = ["| Need | Open |", "|---|---|"]
    for route in routes:
        lines.append(f"| {route['need']} | {route_cell(route, prefix)} |")
    return "\n".join(lines)


def ask_sentence(m: dict, suite: bool) -> str:
    items = ", ".join(m["always_ask"])
    extra = ""
    if suite and m.get("always_ask_suite_extra"):
        extra = f" — {m['always_ask_suite_extra']}"
    return f"Still **always ask** for: {items}{extra} — **if you are the root session**."


